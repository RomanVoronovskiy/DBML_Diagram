package io.github.dbmldiagram.core.database

import io.github.dbmldiagram.core.model.DbmlSourceRange

data class DatabaseName(val schema: String, val name: String) {
    val sql: String get() = "${pgQuote(schema)}.${pgQuote(name)}"
    override fun toString() = "$schema.$name"
}
fun pgQuote(value: String): String = "\"" + value.replace("\"", "\"\"") + "\""
fun pgString(value: String): String = "'" + value.replace("'", "''") + "'"

data class DatabaseColumn(val name: String, val type: String, val nullable: Boolean,
                          val defaultValue: String?, val identity: Boolean = false, val generated: Boolean = false)
data class DatabaseKey(val name: String, val columns: List<String>, val primary: Boolean,val ordinary: Boolean=true)
data class DatabaseIndex(val name: String, val columns: List<String>, val unique: Boolean, val simple: Boolean)
data class DatabaseForeignKey(val name: String, val columns: List<String>, val target: DatabaseName,
                              val targetColumns: List<String>, val onDelete: String, val onUpdate: String,
                              val ordinary: Boolean = true)
data class DatabaseCheck(val name: String, val expression: String, val validated: Boolean)
data class DatabaseTable(val id: DatabaseName, val columns: List<DatabaseColumn>,
                         val keys: List<DatabaseKey> = emptyList(), val indexes: List<DatabaseIndex> = emptyList(),
                         val foreignKeys: List<DatabaseForeignKey> = emptyList(), val checks: List<DatabaseCheck> = emptyList(),
                         val ordinary: Boolean = true)
data class DatabaseSnapshot(val schemas: Set<String>, val tables: List<DatabaseTable>,
                            val enums: Map<DatabaseName, List<String>> = emptyMap(),
                            val relationNames: Set<DatabaseName> = tables.map { it.id }.toSet(),
                            val typeNames: Set<DatabaseName> = enums.keys,
                            val capturedAtMillis: Long = System.currentTimeMillis(),
                            val inspectedSchemas: Set<String> = schemas)

enum class SchemaDifferenceKind { MISSING, CHANGED, DATABASE_ONLY, UNSUPPORTED }
data class SchemaDifference(val id: String, val kind: SchemaDifferenceKind, val objectName: String,
                            val message: String, val tableId: String? = null, val column: String? = null,
                            val range: DbmlSourceRange? = null, val sql: String? = null,
                            val requiresReview: Boolean = false, val dependencies: Set<String> = emptySet())

data class SchemaComparison(val differences: List<SchemaDifference>, val capturedAtMillis: Long) {
    /** Include prerequisites in deterministic creation order; never export an incomplete selection. */
    fun migration(selected: Set<String>): String {
        val byId = differences.associateBy { it.id }
        require(selected.all { byId[it]?.sql != null }) { "Selection contains a difference without a generated migration." }
        val included = linkedSetOf<String>()
        val visiting = mutableSetOf<String>()
        fun add(id: String) {
            if (id in included) return
            require(visiting.add(id)) { "Cyclic migration dependencies." }
            val change = requireNotNull(byId[id]) { "Missing migration prerequisite: $id" }
            require(change.sql != null) { "Resolve prerequisite manually: ${change.objectName}" }
            change.dependencies.forEach(::add)
            visiting.remove(id)
            included += id
        }
        selected.forEach(::add)
        require(included.isNotEmpty()) { "Select at least one change." }
        return buildString {
            appendLine("-- Generated by DBML Diagram: PostgreSQL schema migration.")
            appendLine("-- Catalog snapshot epoch millis: $capturedAtMillis. Compare again before applying.")
            appendLine("BEGIN;")
            appendLine("SET LOCAL lock_timeout = '5s';")
            included.forEach { id ->
                val change = byId.getValue(id)
                if (change.requiresReview) appendLine("-- REVIEW: this change can fail on existing data or change stored values.")
                appendLine(change.sql)
            }
            appendLine("COMMIT;")
        }
    }
}
